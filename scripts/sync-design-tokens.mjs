import { readFile, writeFile } from "node:fs/promises";
const directory = new URL("../packages/recipe-core/", import.meta.url);
const palette = JSON.parse(
  await readFile(new URL("palette.json", directory), "utf8"),
);
const css = `/* Generated by pnpm design:tokens from palette.json. */\n:root {\n${Object.entries(
  palette,
)
  .map(([name, value]) => `  --kitchen-${name}: ${value};`)
  .join("\n")}\n}\n`;
await writeFile(new URL("tokens.css", directory), css);
